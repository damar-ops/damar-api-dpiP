// 👑 DAMAR-MD — فتح / غلق المجموعة
// الأوامر:
// .حل
// .فتح
// .افتح
//
// .سد
// .غلق
// .اغلق
// .اغلاق
// ═══════════════════════════════════════════════════════════════

let handler = async (m, { conn, isAdmin, isBotAdmin, command }) => {
    // خاص بالمجموعات فقط
    if (!m.isGroup) {
        return m.reply('❌ هاد الأمر خدام غير فالمجموعات.');
    }

    // خاص بالأدمن
    if (!isAdmin) {
        return m.reply('🚫 غير الأدمن يقدر يفتح ولا يسد المجموعة.');
    }

    // البوت خاصو يكون أدمن
    if (!isBotAdmin) {
        return m.reply('👑 خاصني نكون أدمن فالمجموعة باش نقدر نبدل الإعدادات.');
    }

    try {
        // ─────────────────────────────────────────────────────
        // 🔓 فتح المجموعة
        // ─────────────────────────────────────────────────────
        if (
            command === 'حل' ||
            command === 'فتح' ||
            command === 'افتح'
        ) {
            await conn.groupSettingUpdate(
                m.chat,
                'not_announcement'
            );

            return m.reply(
                '🔓 *تـم فـتـح الـمـجـمـوعـة*\n\n' +
                '✅ دابا جميع الأعضاء يقدرو يرسلو.\n' +
                '👑 المجموعة مفتوحة للجميع.'
            );
        }

        // ─────────────────────────────────────────────────────
        // 🔒 غلق المجموعة
        // ─────────────────────────────────────────────────────
        if (
            command === 'سد' ||
            command === 'غلق' ||
            command === 'اغلق' ||
            command === 'اغلاق'
        ) {
            await conn.groupSettingUpdate(
                m.chat,
                'announcement'
            );

            return m.reply(
                '🔒 *تـم غـلـق الـمـجـمـوعـة*\n\n' +
                '👑 غير الأدمن يقدرو يرسلو دابا.\n' +
                '🚫 الأعضاء العاديين مايبقاوش يرسلو.'
            );
        }

    } catch (e) {
        console.error('❌ خطأ فتح/غلق المجموعة:', e);

        return m.reply(
            '❌ وقع مشكل وأنا كنبدل إعدادات المجموعة.\n' +
            'تأكد باللي البوت مازال أدمن وحاول من جديد.'
        );
    }
};

handler.help = [
    'حل',
    'فتح',
    'افتح',
    'سد',
    'غلق',
    'اغلق',
    'اغلاق'
];

handler.tags = ['group'];

handler.command = [
    'حل',
    'فتح',
    'افتح',
    'سد',
    'غلق',
    'اغلق',
    'اغلاق'
];

handler.group = true;
handler.admin = true;
handler.botAdmin = true;

export default handler;